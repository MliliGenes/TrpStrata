def write_icons(root, name, inherited, p):
    """A small scalable overlay; inheritance preserves every other icon."""
    inherited = inherited.replace("\n", "").replace("\r", "").replace(",", "")
    inherited = inherited or "Adwaita"
    write(os.path.join(root, "index.theme"),
          f"[Icon Theme]\nName={name}\nComment=trpStrata folder colours\n"
          f"Inherits={inherited},hicolor\nDirectories=scalable/places,scalable/mimetypes\n\n"
          "[scalable/places]\nSize=64\nMinSize=16\nMaxSize=512\nType=Scalable\nContext=Places\n\n"
          "[scalable/mimetypes]\nSize=64\nMinSize=16\nMaxSize=512\nType=Scalable\nContext=MimeTypes\n")
    for icon in FOLDERS:
        write(os.path.join(root, "scalable", "places", icon + ".svg"), folder_svg(icon, p))
    write(os.path.join(root, "scalable", "places", "inode-directory.svg"), folder_svg("folder", p))
    for kind, names in FILE_GROUPS.items():
        svg = file_svg(kind, p)
        for icon in names:
            write(os.path.join(root, "scalable", "mimetypes", icon + ".svg"), svg)
